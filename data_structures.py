# 1. پسندیدہ ایپس کی لسٹ (List)
my_apps = ["VS Code", "GitHub", "Pydroid 3"]

# 2. اپنے کورس کی معلومات کی ڈکشنری (Dictionary)
my_course = {
    "language": "Python",
    "days_completed": 2,
    "status": "Learning"
}

# 3. ان دونوں کو اسکرین پر پرنٹ (Show) کرنا
print("Meri pasandida apps:", my_apps)
print("Kouras ki maloomat:", my_course)

# 4. ڈکشنری سے کوئی ایک خاص چیز پرنٹ کرنا
print("Main abhi seekh raha hoon:", my_course["language"])
